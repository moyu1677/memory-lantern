def normalise_language(value: str | None) -> str:
    return value if value in SUPPORTED_LANGUAGES else "zh"


def translate(text: object, language: str = "zh") -> object:
    """Translate a known UI string; unknown content is returned unchanged."""
    if language != "en" or not isinstance(text, str):
        return text
    translated = text
    for source in sorted(EN_TRANSLATIONS, key=len, reverse=True):
        translated = translated.replace(source, EN_TRANSLATIONS[source])
    # Translate score/time units only when they follow a rendered number. This
    # avoids corrupting words such as “评分” and “分析”.
    translated = re.sub(r"(\d+)\s*分", r"\1 points", translated)
    translated = re.sub(r"(\d+(?:\.\d+)?)\s*秒", r"\1 seconds", translated)
    return translated


def translate_payload(value: object, language: str = "zh") -> object:
    """Recursively localise JSON-compatible response data."""
    if language != "en":
        return value
    if isinstance(value, str):
        return translate(value, language)
    if isinstance(value, list):
        return [translate_payload(item, language) for item in value]
    if isinstance(value, tuple):
        return tuple(translate_payload(item, language) for item in value)
    if isinstance(value, Mapping):
        return {
            key: translate_payload(item, language)
            for key, item in value.items()
        }
    return value
